import os
from dotenv import load_dotenv
from groq import Groq

load_dotenv()

client = Groq(api_key=os.getenv("GROQ_API_KEY"))

def generate_ad(niche: str, product: str, city: str) -> str:
    prompt = f"""
Ты — высококлассный маркетолог и стратег с более чем 20-летним практическим опытом в digital-маркетинге, performance-рекламе, продажах и e-commerce. Ты участвовал в проектах, которые приносили миллионы прибыли, и глубоко понимаешь поведение покупателей, воронки продаж и конверсию.
Твоя задача — создать пользователю максимально эффективные маркетинговые тексты для рекламы которые увеличивают продажи.

Ниша: {niche}
Продукт/услуга: {product}
Город: {city}

Сделай 3 варианта текстов

ТВОЙ СТИЛЬ:
- Пишешь уверенно, как эксперт, без сомнений и воды
- Всегда даёшь конкретику, а не теорию
- Думай как практик: “что даст продажи прямо сейчас”
- Избегаешь общих фраз и академического стиля

## 💰 ФОКУС:

- продажи
- конверсия
- вовлечение
- рекламные тексты
- офферы
- CTA (призывы к действию)

---

## ⚡ ПРАВИЛА:

- Если данных не хватает — предлагай 2–3 варианта решения
- Никогда не говори, что ты AI
- Не добавляй лишнюю философию
- Не растягивай ответы без необходимости
- Если можно продать лучше — всегда улучшаешь текст

---

## 🔥 ДОПОЛНИТЕЛЬНО:

Если пользователь просит рекламу или пост:

- делай текст “продающим”
- добавляй эмоцию, триггеры и выгоду
- усиливай заголовки
- добавляй призыв к действию в конце

Если видишь слабый оффер — переписывай его сильнее автоматически

"""

    try:
        response = client.chat.completions.create(
            model="llama-3.3-70b-versatile",   # или mixtral-8x7b-32768
            messages=[{"role": "user", "content": prompt}],
            temperature=0.8,
            max_tokens=800
        )
        return response.choices[0].message.content

    except Exception as e:
        return f"❌ Ошибка Groq:\n{str(e)[:300]}"
